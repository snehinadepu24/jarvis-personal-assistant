#!/usr/bin/env python3
"""
Generate TypeScript types from Python protocol definitions.

This ensures Python backend and TypeScript frontend stay in sync.
Run this whenever protocol/*.py changes.

Usage:
    python scripts/generate_types.py
"""

import sys
from pathlib import Path

# Add jarvis to path
sys.path.insert(0, str(Path(__file__).parent.parent / "jarvis"))

from jarvis.protocol.types import EventType, CommandType, ActionType, OrbState, TaskStatus
from jarvis.protocol.constants import (
    API_HOST, API_PORT, API_BASE_URL, WS_URL,
    Route, RiskTier, MemoryTier,
)


def enum_to_typescript_union(enum_class, name: str) -> str:
    """Convert Python Enum to TypeScript union type"""
    values = [f"'{e.value}'" for e in enum_class]
    return f"export type {name} = {' | '.join(values)};\n"


def int_enum_to_typescript(enum_class, name: str) -> str:
    """Convert Python IntEnum to TypeScript enum"""
    lines = [f"export enum {name} {{"]
    for member in enum_class:
        # Convert SNAKE_CASE to PascalCase
        ts_name = ''.join(word.capitalize() for word in member.name.split('_'))
        lines.append(f"  {ts_name} = {member.value},")
    lines.append("}\n")
    return '\n'.join(lines)


def generate_typescript_types() -> str:
    """Generate complete TypeScript definitions"""
    
    output = """// AUTO-GENERATED from jarvis/protocol/ - DO NOT EDIT MANUALLY
// Generated by: python scripts/generate_types.py
// 
// This file is the TypeScript equivalent of jarvis/protocol/types.py and jarvis/protocol/constants.py
// Any changes should be made in Python and regenerated.

"""
    
    output += "// =============================================================================\n"
    output += "// API CONFIGURATION\n"
    output += "// =============================================================================\n\n"
    output += f"export const API_HOST = '{API_HOST}';\n"
    output += f"export const API_PORT = {API_PORT};\n"
    output += f"export const API_BASE_URL = '{API_BASE_URL}';\n"
    output += f"export const WS_URL = '{WS_URL}';\n\n"
    
    output += "// =============================================================================\n"
    output += "// EVENT TYPES - Backend → Frontend\n"
    output += "// =============================================================================\n\n"
    output += enum_to_typescript_union(EventType, "EventType")
    output += "\n"
    
    output += "// =============================================================================\n"
    output += "// COMMAND TYPES - Frontend → Backend\n"
    output += "// =============================================================================\n\n"
    output += enum_to_typescript_union(CommandType, "CommandType")
    output += "\n"
    
    output += "// =============================================================================\n"
    output += "// ACTION TYPES\n"
    output += "// =============================================================================\n\n"
    output += enum_to_typescript_union(ActionType, "ActionType")
    output += "\n"
    
    output += "// =============================================================================\n"
    output += "// UI STATES\n"
    output += "// =============================================================================\n\n"
    output += enum_to_typescript_union(OrbState, "OrbState")
    output += "\n"
    output += enum_to_typescript_union(TaskStatus, "TaskStatus")
    output += "\n"
    
    output += "// =============================================================================\n"
    output += "// ROUTES (IntEnum)\n"
    output += "// =============================================================================\n\n"
    output += int_enum_to_typescript(Route, "Route")
    output += "\n"
    
    output += "// =============================================================================\n"
    output += "// RISK TIERS (IntEnum)\n"
    output += "// =============================================================================\n\n"
    output += int_enum_to_typescript(RiskTier, "RiskTier")
    output += "\n"
    
    output += "// =============================================================================\n"
    output += "// MEMORY TIERS (IntEnum)\n"
    output += "// =============================================================================\n\n"
    output += int_enum_to_typescript(MemoryTier, "MemoryTier")
    
    return output


def main():
    """Generate and write TypeScript types"""
    output_path = Path(__file__).parent.parent / "apps" / "desktop" / "src" / "types" / "protocol.ts"
    
    print(f"Generating TypeScript types from Python protocol...")
    
    typescript_code = generate_typescript_types()
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(typescript_code, encoding='utf-8')
    
    print(f"✓ Generated {output_path}")
    print(f"  Lines: {len(typescript_code.splitlines())}")
    print(f"  Size: {len(typescript_code)} bytes")


if __name__ == "__main__":
    main()
